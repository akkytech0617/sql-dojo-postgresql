export function explainSqlState(code: string): JapaneseError {
  const [title, explanation, tip] = messages[code] ?? classes[code.slice(0, 2)] ??
    ['データベースエラー', 'SQL の実行中にエラーが発生しました。', 'エラーコードとメッセージを確認してください。']
  return { title, explanation, tip }
}
export function serializeSqlError(error: unknown): SqlError {
  const source: Record<string, unknown> = error instanceof Error ? error as Error & Record<string, unknown> : {}
  const code = typeof source.code === 'string' ? source.code : 'XX000'
  const result: SqlError = { code, message: typeof source.message === 'string' ? source.message : '不明なエラー', ja: explainSqlState(code) }
  for (const key of ['detail', 'hint', 'position', 'where', 'severity'] as const) {
    if (typeof source[key] === 'string') result[key] = source[key]
  }
  return result
}
